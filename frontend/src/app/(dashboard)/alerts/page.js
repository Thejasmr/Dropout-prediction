"use client";

import React, { useState } from "react";
import Link from "next/link";
import { Bell, CheckCheck, RefreshCw } from "lucide-react";
import { Card, CardContent } from "@/components/ui/Card";
import { Badge } from "@/components/ui/Badge";
import { Button } from "@/components/ui/Button";
import { Select } from "@/components/ui/Select";
import { useAlerts } from "@/hooks/useAlerts";

export default function AlertsPage() {
  const [severityFilter, setSeverityFilter] = useState("");
  const [readFilter, setReadFilter] = useState(null);

  const { data, isLoading, isError, refetch, markRead } = useAlerts({
    severity: severityFilter,
    is_read: readFilter,
  });

  const alerts = data?.items ?? (Array.isArray(data) ? data : []);

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 dark:text-slate-100">Risk Alert Centre</h1>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            Live alerts generated by the prediction engine from real student data
          </p>
        </div>
        <Button size="sm" variant="outline" onClick={() => refetch()} className="gap-1.5">
          <RefreshCw className="w-3.5 h-3.5" /> Refresh
        </Button>
      </div>

      {/* Filters */}
      <div className="flex flex-wrap gap-3">
        <Select
          value={severityFilter}
          onChange={(e) => setSeverityFilter(e.target.value)}
          options={[
            { value: "",         label: "All Severities" },
            { value: "critical", label: "🔴 Critical" },
            { value: "warning",  label: "🟡 Warning" },
            { value: "info",     label: "🔵 Info" },
          ]}
          className="w-48"
        />
        <Select
          value={readFilter === null ? "" : String(readFilter)}
          onChange={(e) => setReadFilter(e.target.value === "" ? null : e.target.value === "true")}
          options={[
            { value: "",      label: "All Alerts" },
            { value: "false", label: "Unread Only" },
            { value: "true",  label: "Read Only" },
          ]}
          className="w-44"
        />
      </div>

      {/* Error */}
      {isError && (
        <div className="p-4 rounded-xl bg-red-50 dark:bg-red-950/30 border border-red-200 text-xs text-red-600">
          Failed to load alerts.{" "}
          <button onClick={() => refetch()} className="underline font-semibold">Retry</button>
        </div>
      )}

      {/* Alert List */}
      <div className="space-y-3">
        {isLoading ? (
          [...Array(5)].map((_, i) => (
            <div key={i} className="h-20 rounded-xl bg-slate-100 dark:bg-slate-800 animate-pulse" />
          ))
        ) : alerts.length === 0 ? (
          <Card>
            <CardContent className="py-16 text-center">
              <Bell className="w-8 h-8 text-slate-300 mx-auto mb-3" />
              <p className="text-sm text-slate-400">No alerts match your filters.</p>
              <p className="text-xs text-slate-400 mt-1">Alerts are generated automatically when student risk crosses a threshold.</p>
            </CardContent>
          </Card>
        ) : (
          alerts.map((alert) => (
            <div
              key={alert.id}
              className={`p-4 rounded-xl border transition-colors ${
                alert.is_read
                  ? "bg-white dark:bg-slate-900/40 border-slate-100 dark:border-slate-800"
                  : "bg-red-50/30 dark:bg-red-950/10 border-red-200 dark:border-red-900/40"
              }`}
            >
              <div className="flex items-start justify-between gap-4">
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 flex-wrap mb-1">
                    <Badge variant={alert.severity === "critical" ? "high" : alert.severity === "warning" ? "medium" : "low"}>
                      {alert.severity?.toUpperCase()}
                    </Badge>
                    {!alert.is_read && (
                      <span className="w-2 h-2 rounded-full bg-red-500 animate-pulse" />
                    )}
                    {alert.student_name && (
                      <Link href={`/students/${alert.student_id}`}
                        className="text-xs font-semibold text-blue-600 dark:text-blue-400 hover:underline truncate">
                        {alert.student_name}
                      </Link>
                    )}
                  </div>
                  <p className="text-sm text-slate-800 dark:text-slate-100 font-medium">{alert.message}</p>
                  <p className="text-xs text-slate-400 mt-1">
                    {alert.created_at ? new Date(alert.created_at).toLocaleString() : ""}
                  </p>
                </div>
                {!alert.is_read && (
                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={() => markRead(alert.id)}
                    className="gap-1 text-xs shrink-0"
                  >
                    <CheckCheck className="w-3.5 h-3.5" /> Mark Read
                  </Button>
                )}
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
}
